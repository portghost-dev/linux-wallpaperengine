RESCLAMP = (
    "resclamp <0-4>\n"
    "\n"
    "Caps the size a scene is drawn at, as a multiple of your largest screen.\n"
    "Lower saves video memory. It never enlarges anything, and turning it off\n"
    "can remove blur this cap caused. Decimals work; 0 or below means no cap.\n"
    "\n"
    "Default 1. Takes effect at the next service restart, or at the next show\n"
    "for one wallpaper. effectclamp is the same cap for glow, blur and other\n"
    "effect layers, set on its own.\n"
    "\n"
    "One wallpaper:  wallpaper <wallpaper> resclamp 0\n"
    "\n"
    "Examples:\n"
    "  resclamp 0          no cap: draw at the artwork's full size\n"
    "  resclamp 1.5        up to one and a half screens\n"
    "  resclamp load       back to what your files say\n"
    "  get resclamp        print the current value\n"
    "\n"
    "Also found by: resolution, sharpness, blur, video memory.\n"
)


    "While the schedule is off you can fill it in one piece at a time. schedule on\n"
    "checks that day and night have different times and different playlists.\n"
    "A playlist you switch to by hand stays until the next start time.\n"
    "\n"
    "Example, starting from nothing:\n"
    "  playlist                            see your playlists, numbered\n"
    "  schedule day playlist 1             \n"
    "  schedule night playlist 2           \n"
    "  schedule on                         day starts at 08:00 and night at 20:00 until you change them\n"
    "\n"
    "Swapping day and night: schedule off, set both playlists, schedule on.\n"

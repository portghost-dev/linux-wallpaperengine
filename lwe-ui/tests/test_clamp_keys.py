"""The two clamp numbers are saved settings, SSFACTOR and CLAMPCOMPOSITES, in settings.conf and in
each wallpaper's file; an absent key reads the file's RENDER_RESOLUTION word per number.

settings.load and the settings restore map the word for a key the file or the archive lacks; a
whole-file save materializes the same numbers and keeps the word; the env file is byte-identical
for every old word and writes a number only when it differs from 1; the show resolver sends each
number a wallpaper decides, own or from its word, clamped, never a non-finite one; the wallpaper
store keeps presence raw, so a revert restores absence; an unset writes the `KEY=` marker or a 1
only where the word would otherwise decide; the clean-up keeps the markers; the push rows treat
the pair as restart settings and wallpaper build keys.

Run: PYTHONPATH=src python3 tests/test_clamp_keys.py
"""
